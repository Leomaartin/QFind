async function seedBeautyPlaces() {
  const country = await prisma.country.findFirst({ where: { name: "Argentina" } });
  const state = await prisma.state.findFirst({ where: { name: "Buenos Aires" } });
  const city = await prisma.city.findFirst({ where: { name: "Zárate" } });

  if (!country || !state || !city) {
    throw new Error(`Country, state or city not found`);
  }

  console.log(`Starting seed for 80 Beauty & Aesthetics businesses in Zárate...`);
  let createdCount = 0;
  let updatedCount = 0;

  for (const place of beautyPlaces) {
    let user = await prisma.user.findUnique({ where: { email: place.email } });
    if (!user) {
      user = await prisma.user.create({
        data: {
          google_id: `google_${place.email}`,
          nombre: place.name,
          email: place.email,
          foto: place.image,
        },
      });
    }

    const existingService = await prisma.service.findUnique({
      where: { userId: user.id },
    });

    let service;
    if (existingService) {
      service = await prisma.service.update({
        where: { id: existingService.id },
        data: {
          name: place.name,
          label: place.label,
          description: place.description,
          phone: place.phone,
          instagram: place.instagram,
          email: place.email,
          image: place.image,
          active: true,
          validated: true,
          paid: true,
          countryId: country.id,
          stateId: state.id,
          cityId: city.id,
          categoryId: place.categoryId,
          subcategoryId: place.subcategoryId,
        },
      });
      updatedCount++;
    } else {
      service = await prisma.service.create({
        data: {
          name: place.name,
          label: place.label,
          description: place.description,
          phone: place.phone,
          instagram: place.instagram,
          email: place.email,
          image: place.image,
          active: true,
          validated: true,
          paid: true,
          countryId: country.id,
          stateId: state.id,
          cityId: city.id,
          categoryId: place.categoryId,
          subcategoryId: place.subcategoryId,
          userId: user.id,
        },
      });
      createdCount++;
    }

    const existingPlan = await prisma.plan.findFirst({
      where: { serviceId: service.id },
    });

    if (!existingPlan) {
      const now = new Date();
      const endDate = new Date(now.getTime() + 365 * 24 * 60 * 60 * 1000);
      await prisma.plan.create({
        data: {
          startDate: now,
          endDate: endDate,
          paymentStatus: true,
          planTypeId: place.planTypeId || 4,
          serviceId: service.id,
        },
      });
    }
  }

  console.log(`Seed completed! Created: ${createdCount}, Updated: ${updatedCount}`);

  // Summary per subcategory
  for (let scId = 1; scId <= 8; scId++) {
    const subcat = await prisma.subcategory.findUnique({ where: { id: scId } });
    const count = await prisma.service.count({
      where: {
        cityId: city.id,
        categoryId: 1,
        subcategoryId: scId,
      },
    });
    console.log(`Subcategory ${scId} (${subcat?.label}): ${count} active services in Zárate`);
  }

  const totalBeauty = await prisma.service.count({
    where: { cityId: city.id, categoryId: 1 },
  });
  console.log(`\nTOTAL Beauty & Aesthetics services in Zárate: ${totalBeauty}`);
}

seedBeautyPlaces()
